"""Summarise robustness-suite grade JSONs into reports/robustness.md (measured values only)."""
from __future__ import annotations

import json
import sys
from pathlib import Path


def pct(x):
    return "—" if x is None else f"{x * 100:+.1f}%"


def main(outdir: str, dest: str):
    rows, notes = [], []
    for j in sorted(Path(outdir).glob("*.json")):
        try:
            g = json.loads(j.read_text(encoding="utf-8"))
        except Exception as e:  # a failed run is a finding, not something to hide
            rows.append(f"| {j.stem} | **run failed** ({e}) | | | | | | |")
            continue
        out = (Path(outdir) / f"{j.stem}.out").read_text(encoding="utf-8", errors="replace")
        rc = next((l.split("exit=")[1].split()[0] for l in out.splitlines() if "run.sh exit=" in l), "?")
        d = g["delta_vs_baseline"]["ALL"]
        v = g["controller_changes"]["verdicts"]
        harm = [f"{c['workflow_id']} v{c['version']} {'/'.join(c['dims'])} ({c['engage_delta']:+.3f}/{c['did_health_delta']:+.3f})"
                for c in g["controller_changes"]["detail"] if c["verdict"] == "harmful"]
        inc = []
        for i in g["incidents"]:
            if "mttr_minutes" in i:
                inc.append(f"prompt {i['workflow']}: MTTR {i['mttr_minutes']} min" if i["mttr_minutes"] is not None
                           else f"prompt {i['workflow']}: **not fixed**")
            if i["type"] == "did_flagged":
                share = i["flagged_did_share_by_day"]
                inc.append(f"DID {i['workflow']}: share by day {list(share.values())[:4]}")
        dec = [f"{k}: {list(s.values())}" for k, s in g["decaying_variant_share_after_onset"].items()]
        gv = g["governance"]
        errs = winners = exps = "?"
        dbp = Path(outdir) / f"{j.stem}.db"
        if dbp.exists():   # from our own audit store: decision errors, experiments run, winners declared
            import sqlite3
            c = sqlite3.connect(f"file:{dbp.as_posix()}?mode=ro", uri=True)
            errs = c.execute("SELECT COUNT(*) FROM decisions WHERE kind='error'").fetchone()[0]
            exps = c.execute("SELECT COUNT(*) FROM experiments").fetchone()[0]
            winners = c.execute("SELECT COUNT(*) FROM decisions WHERE kind='experiment_winner'").fetchone()[0]
            c.close()
        prim = []
        for wid, k in g["delta_vs_baseline"].items():
            if wid != "ALL":
                prim.append(f"{wid} {pct(k['conclusion_rate'])}")
        rows.append(f"| {j.stem} | {rc} | {pct(d['conclusion_rate'])} ({', '.join(prim)}) | {pct(d['pickup_rate'])} | "
                    f"{pct(d['engagement_rate'])} | {g['controller_changes']['count']} ({v.get('beneficial', 0)}+/"
                    f"{v.get('neutral', 0)}=/{v.get('harmful', 0)}-) | exp {gv['decisions'].get('expired', 0)}, lapsed "
                    f"{gv['lapsed']}, conflicts {gv['apply_conflicts']}, auto-denied {gv['auto_apply_rejected']}, "
                    f"peak/24h {max(gv['peak_requests_per_24h'].values(), default=0)} | {g['credits_used']:.0f} | "
                    f"{winners}/{exps} | {errs} |")
        notes.append(f"**{j.stem}** — harmful: {'; '.join(harm) or 'none'}. Incidents: {'; '.join(inc) or 'none'}. "
                     f"Decay: {'; '.join(dec) or 'n/a'}")
    md = ["# Robustness suite (our own hidden-like scenarios)", "",
          "Generated by `scripts/make_robustness_scenarios.py`, run by `scripts/robustness.sh` (one Linux container "
          "per scenario, 2 vCPU / 2 GB; native fallback when Docker is down). Same schema as the public scenarios, different truth, policies and incidents. "
          "Numbers are the simulator grader's output.", "",
          "| scenario | run.sh exit | conclusion Δ (per workflow) | pickup Δ | engagement Δ | changes (+/=/-) | governance | credits | winners / experiments | decision errors |",
          "|---|---|---|---|---|---|---|---|---|---|", *rows,
          "", "*winners / experiments* counts `experiment_winner` decisions in our own audit store. On `r3_null_effects` "
          "(no true effects) every winner is a false winner — that, not the grader's harmful count (which marks every "
          "null-scenario change neutral), is the false-winner measurement. *decision errors* must be 0.", "", *[f"- {n}" for n in notes], ""]
    Path(dest).write_text("\n".join(md), encoding="utf-8", newline="\n")
    print("\n".join(md))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
