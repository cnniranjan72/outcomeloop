"""Build evidence/: the reviewer's package, generated from the final run stores and reports (nothing typed by hand).

    python scripts/build_evidence.py        # after the final scenario runs (state/*.db) and reports exist

Writes evidence/*.txt (real command output, first line = the command) and evidence/RESULTS.md (every number parsed
from reports/*.md, each with its source; projections labelled as projections). evidence/README.md is the hand-written
20-minute guide that points into these files.
"""
from __future__ import annotations

import os
import re
import sqlite3
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "evidence"
P1, P2 = ROOT / "state" / "public_01_dev.db", ROOT / "state" / "public_02_incidents.db"


def run(db: Path, *args: str) -> str:
    env = dict(os.environ, PYTHONPATH=str(ROOT / "src"), PYTHONUTF8="1", OUTCOMELOOP_DB=str(db))
    r = subprocess.run([sys.executable, "-m", "outcomeloop", *args], capture_output=True, text=True, env=env,
                       cwd=ROOT, encoding="utf-8")
    if r.returncode not in (0, 1):
        raise SystemExit(f"{args}: {r.stderr}")
    return r.stdout


def save(name: str, db: Path, *args: str, note: str = ""):
    shown = " ".join(a if " " not in a and "*" not in a else f'"{a}"' for a in args)
    body = f"$ python -m outcomeloop --db {db.relative_to(ROOT).as_posix()} {shown}\n"
    if note:
        body += f"# {note}\n"
    (OUT / name).write_text(body + "\n" + run(db, *args), encoding="utf-8", newline="\n")
    print("wrote", (OUT / name).relative_to(ROOT))


def q1(db: Path, sql: str, args=()):
    c = sqlite3.connect(f"file:{db}?mode=ro", uri=True)
    try:
        return c.execute(sql, args).fetchone()
    finally:
        c.close()


def results_md():
    r = lambda n: (ROOT / "reports" / n).read_text(encoding="utf-8")
    p1, p2, p3, rob, crash, mem, scal = (r("public_01_dev.md"), r("public_02_incidents.md"), r("public_03.md"),
                                         r("robustness.md"), r("crash_recovery.md"), r("memory.md"), r("scaling.md"))
    allrow = lambda md: [c.strip() for c in next(l for l in md.splitlines() if l.startswith("| ALL |")).strip("|").split("|")]
    applied = lambda md: re.search(r"(\d+) applied — ([^\n]*)", md).groups()
    mttr = re.search(r'"mttr_minutes": (\d+)', p2).group(1)
    crash_line = re.search(r"Result: (\w+) \((\d+) checks: [^)]*\)", crash).group(0)
    rows = [l for l in rob.splitlines() if l.startswith("| ") and not l.startswith(("| scenario", "|---"))]
    ok = sum(1 for l in rows if l.split("|")[2].strip() == "0")
    nw = ne = 0
    for l in rows:
        if "r3_null_effects" in l:
            w, e = l.strip().strip("|").split("|")[-2].strip().split("/")
            nw, ne = nw + int(w), ne + int(e)
    m1 = re.search(r"\*\*controller seconds per simulated day\*\* \| \*\*([\d.]+) / ([\d.]+)\*\* \| \*\*([\d.]+) / ([\d.]+)\*\*", scal)
    proj = re.search(r"gives ≈ \*\*(\d+) s", scal)
    mm = re.search(r"peak controller memory \| ([\d,]+) MB \| \*\*([\d,]+) MB\*\*", mem)
    tests = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], capture_output=True,
                           text=True, cwd=ROOT, encoding="utf-8").stdout.strip().splitlines()[-1]
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
    a1, a2 = applied(p1), applied(p2)
    lines = [
        "# Results — every number parsed from a report (source in the last column)", "",
        f"Generated by `scripts/build_evidence.py` at commit `{head}`. **Measured** = from a run or test; "
        "**projected** = arithmetic on measurements, never presented as a run.", "",
        "| what | value | kind | source |", "|---|---|---|---|",
        f"| public_01 conclusion rate vs no-op baseline | {allrow(p1)[2]} ({a1[0]} changes: {a1[1]}) | measured | `reports/public_01_dev.md` |",
        f"| public_02 conclusion rate vs no-op baseline | {allrow(p2)[2]} ({a2[0]} changes: {a2[1]}) | measured | `reports/public_02_incidents.md` |",
        f"| public_02 unsafe-prompt time to fix (grader MTTR) | {mttr} min | measured | `reports/public_02_incidents.md` |",
        f"| public_03 load conclusion rate | {allrow(p3)[2]} | measured | `reports/public_03.md` |",
        f"| peak controller memory, public_03 | {mm.group(2)} MB (was {mm.group(1)} MB before the streaming fix) | measured | `reports/memory.md` |",
        f"| controller s per simulated day, 4 vCPU / 8 GB container, 1× / 3× | {m1.group(1)}–{m1.group(2)} / {m1.group(3)}–{m1.group(4)} s | measured | `reports/scaling.md` |",
        f"| controller s per simulated day at 10× | ≈ {proj.group(1)} s (target 600 s) | **projected** | `reports/scaling.md` |",
        f"| robustness suite runs exiting 0 | {ok}/{len(rows)} | measured | `reports/robustness.md` |",
        f"| false winners on the no-effects scenario | {nw} in {ne} experiments | measured | `reports/robustness.md` |",
        f"| crash recovery | {crash_line} after 9 hard kills | measured | `reports/crash_recovery.md` |",
        f"| test suite (`pytest -q`) | {tests} | measured | run by this script |",
        "", "Known limitations are in `docs/ADVERSARIAL_TESTING.md` §6 and SUBMISSION.md §13; the scale bottleneck and",
        "the sharding prototype in `reports/scaling.md`.",
    ]
    (OUT / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote evidence/RESULTS.md")


def main():
    OUT.mkdir(exist_ok=True)
    exp = q1(P1, "SELECT experiment_id FROM decisions WHERE kind='decay_detected' ORDER BY decision_id LIMIT 1")
    if exp:
        save("lifecycle_experiment_public01.txt", P1, "lifecycle", exp[0],
             note="one experiment, end to end: design, daily looks, winner checks, approval, promotion, decay, rollback")
    inc = q1(P2, "SELECT incident_id FROM decisions WHERE kind='incident_opened' ORDER BY decision_id LIMIT 1")
    if inc:
        save("lifecycle_incident_public02.txt", P2, "lifecycle", inc[0],
             note="the supervisor's unsafe prompt: probe, incident, known-good fix, approval, apply, verification")
        d = q1(P2, "SELECT decision_id FROM decisions WHERE kind='incident_opened' ORDER BY decision_id LIMIT 1")[0]
        save("decision_incident_opened_public02.txt", P2, "decision", str(d),
             note="one decision in full: reasoning, evidence, linked incident, before / after")
    did = q1(P2, "SELECT d2.proposal_id FROM decisions d1 JOIN decisions d2 ON d2.wf=d1.wf AND d2.kind='auto_apply'"
                 " AND d2.minute>=d1.minute AND d2.proposal_id IS NOT NULL WHERE d1.kind='did_health' AND d1.summary"
                 " LIKE '%-> degraded' ORDER BY d1.decision_id, d2.decision_id LIMIT 1")
    if did:
        save("lifecycle_caller_id_public02.txt", P2, "lifecycle", did[0],
             note="moving traffic off a degraded caller ID through the policy-permitted auto route")
    save("status_public02.txt", P2, "status")
    save("audit_incidents_public02.txt", P2, "audit", "--kind", "incident_*",
         note="audit rows carry their decision id: drill in with `decision <id>`")
    results_md()


if __name__ == "__main__":
    main()
