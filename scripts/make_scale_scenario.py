"""Generate a K-times version of public_03_load for a measured scaling curve (test tooling only).

    python scripts/make_scale_scenario.py 3 2      # 3x workflows (36), 2 days -> tests/scale/load_x3_d2.yaml

Every workflow of public_03 is copied K times under new ids (tenant ids suffixed too), same schema; days and
history are shortened so the simulator itself finishes in reasonable time.
"""
import copy
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def main(k: int, days: int):
    sc = yaml.safe_load((ROOT / "scenarios" / "public_03_load.yaml").read_text(encoding="utf-8"))
    tenants = []
    for r in range(k):
        for t in sc["tenants"]:
            t2 = copy.deepcopy(t)
            t2["id"] = f"{t['id']}_r{r}"
            for w in t2["workflows"]:
                w["id"] = f"{w['id']}_r{r}"
            tenants.append(t2)
    sc.update(name=f"load_x{k}_d{days}", tenants=tenants, days=days, history_days=3, incidents=[])
    sc["effects"] = [dict(e, workflow=f"{e['workflow']}_r{r}") for r in range(k) for e in sc.get("effects", [])
                     if e["workflow"] != "*"] + [e for e in sc.get("effects", []) if e["workflow"] == "*"]
    out = ROOT / "tests" / "scale" / f"load_x{k}_d{days}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("# Generated by scripts/make_scale_scenario.py (test tooling).\n" + yaml.safe_dump(sc, sort_keys=False))
    print(out.relative_to(ROOT), sum(len(t["workflows"]) for t in tenants), "workflows")


if __name__ == "__main__":
    main(int(sys.argv[1]), int(sys.argv[2]))
