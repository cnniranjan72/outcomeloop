"""Rebuild the measured sections of reports/crash_recovery.md (header, §2 kill schedule, §3 reconciliation, §4
verification, §5 outcomes) from reports/crash_recovery_timeline.json and state/crash_public_02.db.
The narrative sections (§1 method, §6 bugs found, §7 what a crash loses, §8 reproduce) are kept as written.

    python scripts/crash_report.py
"""
from __future__ import annotations

import json
import re
import sqlite3
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "reports"


def main():
    t = json.loads((R / "crash_recovery_timeline.json").read_text(encoding="utf-8"))
    old = (R / "crash_recovery.md").read_text(encoding="utf-8")
    sec = lambda n: re.search(r"(^## %d\..*?)(?=^## \d+\.|\Z)" % n, old, re.S | re.M).group(1).rstrip() + "\n"
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    v = t["verification"]
    checks = v["checks"] if isinstance(v, dict) and "checks" in v else v
    n_pass = sum(c.get("status") == "PASS" for c in checks)
    n_fail = sum(c.get("status") == "FAIL" for c in checks)
    kills = [l for l in t["launches"] if l.get("kill")]
    L = ["# Crash-recovery evidence — public_02_incidents", "",
         f"**Result: {'PASS' if n_fail == 0 else 'FAIL'} ({len(checks)} checks: {n_pass} PASS, "
         f"{len(checks) - n_pass - n_fail} INFO, {n_fail} FAIL).** The controller was hard-killed {len(kills)} times "
         f"({t['kill_method']}) during one run of public_02 and restarted against the same SQLite file each time; the "
         f"final launch ran the scenario to the end. Report generated at commit `{head}` (the run used the decision logic of commit `{head}`). Platform: {t['platform']}, Python "
         f"{t['python']}. Run started {t['started']}.", "",
         "Every number below comes from `reports/crash_recovery_timeline.json` (written by `scripts/crash_recovery.py`) "
         "and the controller's own audit store `state/crash_public_02.db`; this file is regenerated by "
         "`scripts/crash_report.py`. A graceful shutdown is never used.", "", sec(1),
         "## 2. Kill schedule", "",
         "| # | aim | sim time at kill | what was in flight (from our DB, read-only) | DB state right after the kill |",
         "|---|---|---|---|---|"]
    for l in kills:
        k, db = l["kill"], l.get("db_after_kill") or {}
        st = (f"chunks {db.get('chunks')}, calls {db.get('calls'):,}, decisions {db.get('decisions')}, proposals "
              f"{db.get('proposals_by_state')}, credit calls in flight {len((db.get('in_flight') or {}).get('credits_ledger_sent', []))}"
              if db.get("db_exists") and db.get("calls") is not None else "nothing committed yet")
        L.append(f"| {l['launch']} ({k['label']}) | {k['aim']} | {k.get('sim_label_last_polled')} | "
                 f"{str(k.get('reason', '')).replace('|', '/')} | {st} |")
    L += ["", f"Launch {t['launches'][-1]['launch']} ran to completion and exited {t['launches'][-1].get('exit_code')}.", "",
          "## 3. Restart reconciliation (from the `decisions` table)", "", "```"]
    c = sqlite3.connect(ROOT / "state" / "crash_public_02.db")
    for m, k, s in c.execute("SELECT minute, kind, summary FROM decisions WHERE kind IN ('controller_start',"
                             "'controller_restart','recovery_reconcile','controller_finish') ORDER BY decision_id"):
        d, mod = divmod(m, 1440)
        L.append(f"D{d} {mod // 60:02d}:{mod % 60:02d}  {k:20s} {s[:150]}")
    L += ["```", "", "## 4. Verification results (`scripts/verify_recovery.py`)", "",
          "| # | check | result | evidence |", "|---|---|---|---|"]
    for i, ch in enumerate(checks, 1):
        L.append(f"| {i} | {ch.get('check') or ch.get('name')} | {ch.get('status')} | {str(ch.get('detail', ''))[:220].replace('|', '/')} |")
    grade = (R / "crash_public_02_grade.md").read_text(encoding="utf-8")
    tab = grade.split("## Changes applied")[0].split("(no-op controller)")[-1].strip()
    clean = (R / "public_02_incidents.md").read_text(encoding="utf-8").split("## Changes applied")[0].split("(no-op controller)")[-1].strip()
    L += ["", "## 5. Outcomes with kills vs the uninterrupted run", "", "With kills (`reports/crash_public_02_grade.md`):",
          "", tab, "", "Uninterrupted (`reports/public_02_incidents.md`):", "", clean, "",
          "The runs are not bit-identical and are not expected to be: a restart changes when in wall-clock terms each "
          "decision is taken relative to the simulator's random stream. What must hold — and does — are the "
          "invariants in §4, and outcomes of the same size.", ""]
    out = "\n".join(L) + "\n" + sec(6) + "\n" + sec(7) + "\n" + sec(8)
    (R / "crash_recovery.md").write_text(out, encoding="utf-8", newline="\n")
    print(L[2])


if __name__ == "__main__":
    main()
